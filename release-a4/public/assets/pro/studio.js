  if(ctx.route==='library'||ctx.route==='universe')return practice('Yeniden bakılacak sözcükler',weak.length?`Yanlış sayısı doğrularından fazla olan ${weak.length} sözcük var.`:'Tekrar gerektiren sözcükler, yanıtların biriktikçe burada görünecek.',weak);
