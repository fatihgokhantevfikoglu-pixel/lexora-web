function playCue(kind){
  if(document.documentElement.dataset.proSound!=='on')return;
  try{
    const AC=window.AudioContext||window.webkitAudioContext;if(!AC)return;
    const audio=playCue.context||(playCue.context=new AC());audio.resume().catch(()=>{});
    const notes=kind==='success'?[520,695]:kind==='review'?[310,265]:[390];
    notes.forEach((pitch,i)=>{
      const start=audio.currentTime+i*.09,osc=audio.createOscillator(),gain=audio.createGain();osc.type='sine';osc.frequency.value=pitch;
      gain.gain.setValueAtTime(.0001,start);gain.gain.exponentialRampToValueAtTime(.045,start+.009);gain.gain.exponentialRampToValueAtTime(.0001,start+.095);
      osc.connect(gain);gain.connect(audio.destination);osc.start(start);osc.stop(start+.1);
    });
  }catch{}
}

