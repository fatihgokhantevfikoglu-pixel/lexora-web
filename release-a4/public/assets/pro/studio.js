function preferences(ctx){
  const layout=ctx.store.getItem('pro-nav')||'side';
  return {layout:['side','top','bottom'].includes(layout)?layout:'side',sound:ctx.store.getItem('pro-sound')==='on'};
}

function styleShell(ctx){
  const prefs=preferences(ctx);
  document.documentElement.dataset.proNav=prefs.layout;
  document.documentElement.dataset.proSound=prefs.sound?'on':'off';
}

